def create_voltage_divider_circuit():
    """Create voltage divider circuit using circuit-synth (target API)"""
    from circuit_synth import circuit, Component, Net
    
    @circuit(name="voltage_divider")
    def voltage_divider():
        """Simple 2:1 voltage divider - VOUT should be VIN/2"""
        # Components
        r1 = Component(symbol="Device:R", ref="R", value="10k")
        r2 = Component(symbol="Device:R", ref="R", value="10k") 
        
        # Nets (connections)
        vin = Net('VIN')
        vout = Net('VOUT')
        gnd = Net('GND')
        
        # Connections (R1 in series with R2)
        r1[1] += vin   # VIN ---[R1]--- VOUT
        r1[2] += vout  #              |
        r2[1] += vout  #             [R2]
        r2[2] += gnd   #              |
                       #             GND
    
    return voltage_divider()

