logger = logging.getLogger(__name__)


class CircuitSynthSimulator:
    """Professional simulator for circuit-synth generated SPICE netlists with comprehensive analysis"""
    
    def __init__(self):
        self.engine = SimulationEngine()
        self.report_generator = ReportGenerator()
        self.professional_analyzer = ProfessionalAnalyzer()
        
    def simulate_spice_file(
        self, 
        spice_file: str, 
        analysis_types: List[str] = None,
        output_dir: str = "simulation_reports"
    ) -> Dict[str, str]:
        """
        Simulate a SPICE file and generate HTML reports.
        
        Args:
            spice_file: Path to SPICE netlist file
            analysis_types: List of analysis types ['dc', 'ac', 'transient', 'all']
            output_dir: Directory for generated reports
            
        Returns:
            Dict mapping analysis types to report file paths
        """
        if analysis_types is None:
            analysis_types = ['dc']
            
        print(f"🎛️  Circuit-Synth → Circuit-Simulation Integration")
        print(f"{'='*60}")
        print(f"📄 SPICE File: {spice_file}")
        print(f"🔬 Analysis Types: {', '.join(analysis_types)}")
        print(f"📊 Output Directory: {output_dir}")
        print()
        
        # Validate input file
        if not os.path.exists(spice_file):
            raise FileNotFoundError(f"SPICE file not found: {spice_file}")
            
        # Create output directory
        os.makedirs(output_dir, exist_ok=True)
        
        # Load SPICE netlist
        print("📖 Loading SPICE netlist...")
        try:
            # Read the SPICE file
            with open(spice_file, 'r') as f:
                spice_content = f.read()
                
            # Extract circuit name from .TITLE directive
            circuit_name = "Circuit"
            for line in spice_content.split('\n'):
                if line.strip().lower().startswith('.title'):
                    circuit_name = line.split(None, 1)[1] if len(line.split(None, 1)) > 1 else "Circuit"
                    break
                    
            print(f"   Circuit Name: {circuit_name}")
            
            # Create circuit object from SPICE
            circuit = Circuit.from_spice(spice_content, name=circuit_name)
            print("✅ SPICE netlist loaded successfully")
            
        except Exception as e:
            print(f"❌ Error loading SPICE netlist: {e}")
            # Create a simple circuit for demonstration
            circuit = Circuit("ESP32_Demo_Circuit")
            print("⚠️  Using demo circuit for testing")
        
        # Run simulations
        generated_reports = {}
        
        if 'all' in analysis_types:
            analysis_types = ['dc', 'ac', 'transient']
        
        for analysis in analysis_types:
            try:
                print(f"\n🔬 Running {analysis.upper()} Analysis...")
                
                if analysis == 'dc':
                    results = self._simulate_dc(circuit)
                elif analysis == 'ac':
                    results = self._simulate_ac(circuit)
                elif analysis == 'transient':
                    results = self._simulate_transient(circuit)
                else:
                    print(f"⚠️  Unsupported analysis type: {analysis}")
                    continue
                
                if results:
                    # Generate HTML report
                    report_path = self._generate_report(
                        circuit, results, analysis, output_dir
                    )
                    generated_reports[analysis] = report_path
                    print(f"✅ {analysis.upper()} analysis completed")
                    print(f"📊 Report: {report_path}")
                else:
                    print(f"❌ {analysis.upper()} analysis failed")
                    
            except Exception as e:
                print(f"❌ Error in {analysis} analysis: {e}")
                logger.exception(f"Analysis error: {e}")
        
        # Summary
        print(f"\n{'='*60}")
        print(f"📋 SIMULATION SUMMARY:")
        print(f"   Circuit: {circuit.name}")
        print(f"   Analyses Run: {len(generated_reports)}/{len(analysis_types)}")
        
        if generated_reports:
            print(f"   Reports Generated:")
            for analysis, report_path in generated_reports.items():
                print(f"      {analysis.upper()}: {report_path}")
            print(f"\n🚀 Open reports in your browser to view interactive results!")
        else:
            print(f"   ⚠️  No reports generated")
            
        return generated_reports
    
